/* eslint-disable @typescript-eslint/no-explicit-any -- service-role seeding client, loose rows */
import { test, expect, type Page } from "@playwright/test";
import { createClient } from "@supabase/supabase-js";
import { assertLocalE2eTarget } from "./_guard";
import { waitForHydrated } from "./_hydration";

/**
 * The owner's dashboard money tiles agree with the transactions behind them.
 *
 * Until now the only browser assertion was that the labels were visible. This reads the tiles
 * ("Invoiced this month", "Outstanding", "Cash in this month") and checks them, to the penny,
 * against totals computed INDEPENDENTLY here from the invoices and payments tables — and then
 * walks one invoice through its life, asserting each tile moves by exactly the right amount:
 *
 *   draft            → nothing moves (a draft is not billed and is not owed)
 *   sent £1,200.00   → Invoiced +1,200.00 · Outstanding +1,200.00
 *   part-paid £500   → Outstanding +700.00 (netted against the payment) · Cash in +500.00
 *   void £5,000 (new)→ nothing moves (a voided invoice is not revenue and not owed)
 *   paid in full     → Outstanding back to where it started · Cash in +1,200.00 · status paid
 *
 * And a payment larger than what an invoice still owes is refused (second defect found here:
 * nothing stopped it — a slipped digit marked the invoice paid and inflated cash-in).
 *
 * Defect this found: "Invoiced this month" summed EVERY invoice created this month, drafts and
 * voids included, so the tile overstated billing as soon as a quote was accepted (acceptance
 * creates a draft invoice). Real browser, production build, real Postgres.
 */
const SLUG = "e2e-harness-org";
const TAG = `dm${Date.now().toString(36)}`;
const OUTSTANDING = ["sent", "awaiting_payment", "partially_paid", "overdue"];
const ISSUED = ["sent", "awaiting_payment", "partially_paid", "paid", "overdue"];

function svc() {
  return createClient(assertLocalE2eTarget("dashboard-money-reconciliation.spec.ts"), process.env.SUPABASE_SERVICE_ROLE_KEY!, {
    auth: { persistSession: false, autoRefreshToken: false },
  }) as unknown as { from: (t: string) => any };
}
const pence = (v: unknown) => Math.round(Number(v ?? 0) * 100);

async function tile(page: Page, label: string): Promise<number> {
  const card = page.locator("div.rounded-xl", { has: page.getByText(label, { exact: true }) }).first();
  const text = (await card.locator("div.tabular-nums").first().innerText()).replace(/[^0-9.-]/g, "");
  return Math.round(Number(text) * 100);
}

test.describe.configure({ mode: "serial" });
test.describe("dashboard money tiles reconcile with invoices and payments (browser)", () => {
  test.use({ storageState: "e2e/.auth/owner.json" });
  const db = svc();
  let org = "", customer = "", sentId = "";
  const monthStart = new Date(Date.UTC(new Date().getUTCFullYear(), new Date().getUTCMonth(), 1)).toISOString();
  const due = new Date(Date.now() + 30 * 86_400_000).toISOString().slice(0, 10);

  /** Independent recomputation from the tables (not the app's own helpers). */
  const fromTables = async () => {
    const invoices = ((await db.from("invoices").select("id, status, total, created_at").eq("org_id", org)).data ?? []) as any[];
    const payments = ((await db.from("invoice_payments").select("invoice_id, amount, paid_at").eq("org_id", org)).data ?? []) as any[];
    const paid = new Map<string, number>();
    for (const p of payments) paid.set(p.invoice_id, (paid.get(p.invoice_id) ?? 0) + pence(p.amount));
    let invoiced = 0, outstanding = 0, cashIn = 0;
    for (const i of invoices) {
      if (ISSUED.includes(i.status) && i.created_at >= monthStart) invoiced += pence(i.total);
      if (OUTSTANDING.includes(i.status)) outstanding += Math.max(0, pence(i.total) - (paid.get(i.id) ?? 0));
    }
    for (const p of payments) if (p.paid_at >= monthStart.slice(0, 10)) cashIn += pence(p.amount);
    return { invoiced, outstanding, cashIn };
  };
  const tiles = async (page: Page) => {
    await page.goto("/dashboard");
    await expect(page.getByText("Invoiced this month", { exact: true }).first()).toBeVisible();
    return {
      invoiced: await tile(page, "Invoiced this month"),
      outstanding: await tile(page, "Outstanding"),
      cashIn: await tile(page, "Cash in this month"),
    };
  };
  const invoice = async (status: string, total: number, suffix: string) => {
    const r = await db.from("invoices").insert({
      // `total` is generated by the database (amount + vat_total); totals here are exact at 20% VAT
      org_id: org, customer_id: customer, number: `INV-${TAG}-${suffix}`, status, amount: Math.round((total / 1.2) * 100) / 100, vat_total: Math.round((total - total / 1.2) * 100) / 100, due_date: due,
    }).select("id").single();
    if (r.error) throw new Error(`invoice ${suffix}: ${r.error.message}`);
    return r.data.id as string;
  };
  const pay = async (invoiceId: string, amount: number) => {
    const r = await db.from("invoice_payments").insert({ org_id: org, invoice_id: invoiceId, amount, paid_at: new Date().toISOString().slice(0, 10), reference: `${TAG}-${amount}` });
    if (r.error) throw new Error(`payment: ${r.error.message}`);
  };

  test.beforeAll(async () => {
    org = (await db.from("organizations").select("id").eq("slug", SLUG).maybeSingle()).data?.id;
    if (!org) throw new Error("harness org not found — did globalSetup run?");
    customer = (await db.from("customers").insert({ org_id: org, name: `Money ${TAG}` }).select("id").single()).data.id;
  });

  test("the tiles equal the totals recomputed from the tables, and each step of an invoice's life moves them by exactly the right amount", async ({ page }) => {
    test.setTimeout(120_000);
    const base = await tiles(page);
    expect(base, "tiles = independent recomputation (baseline)").toEqual(await fromTables());

    await invoice("draft", 900, "draft");
    expect(await tiles(page), "a draft is not billed and not owed").toEqual(base);

    sentId = await invoice("sent", 1200, "sent");
    let now = await tiles(page);
    expect(now).toEqual({ invoiced: base.invoiced + 120_000, outstanding: base.outstanding + 120_000, cashIn: base.cashIn });

    await pay(sentId, 500);
    now = await tiles(page);
    expect(now, "part-payment nets the balance").toEqual({ invoiced: base.invoiced + 120_000, outstanding: base.outstanding + 70_000, cashIn: base.cashIn + 50_000 });
    expect((await db.from("invoices").select("status").eq("id", sentId).single()).data.status).toBe("partially_paid");

    await invoice("void", 5000, "void");
    expect(await tiles(page), "a voided invoice is neither revenue nor owed").toEqual(now);

    await pay(sentId, 700);
    now = await tiles(page);
    expect(now, "paid in full").toEqual({ invoiced: base.invoiced + 120_000, outstanding: base.outstanding, cashIn: base.cashIn + 120_000 });
    expect((await db.from("invoices").select("status").eq("id", sentId).single()).data.status).toBe("paid");

    // and the page still agrees with the tables at the end
    expect(now).toEqual(await fromTables());
  });

  test("recording a payment larger than what is owed is refused in the app; the exact balance is accepted", async ({ page }) => {
    const id = await invoice("sent", 300, "over");
    const rows = async () => ((await db.from("invoice_payments").select("amount").eq("invoice_id", id)).data ?? []) as any[];

    await page.goto(`/invoices/${id}`);
    const record = page.getByRole("button", { name: "Record payment" });
    await waitForHydrated(record);
    // a slipped digit: £3,000 against a £300.00 invoice
    await page.locator('input[name="amount"]').fill("3000");
    await record.click();
    await expect(page.getByText(/more than the £300\.00 still owed on this invoice/)).toBeVisible();
    expect(await rows(), "nothing was recorded").toHaveLength(0);
    expect((await db.from("invoices").select("status").eq("id", id).single()).data.status).toBe("sent");

    // the exact balance goes through and settles the invoice
    await page.locator('input[name="amount"]').fill("300");
    await record.click();
    await expect.poll(async () => (await rows()).length).toBe(1);
    expect(pence((await rows())[0].amount)).toBe(30_000);
    await expect.poll(async () => (await db.from("invoices").select("status").eq("id", id).single()).data.status).toBe("paid");
  });
});
