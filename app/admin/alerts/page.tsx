const PHONE_DIGITS_RE = /[^\d+]/g;

function AlertCard({
  alert,
  contact,
}: {
  alert: AlertWithState;
  contact: OwnerContact | undefined;
}) {
  const phone = (contact?.phone ?? "").replace(PHONE_DIGITS_RE, "");
  const email = contact?.email ?? "";

  return (
    <li
      className={`rounded-xl border bg-white p-4 shadow-sm ${
        alert.resolved
          ? "border-emerald-200 opacity-75"
          : alert.snoozed
            ? "border-slate-200 opacity-75"
            : alert.unread
              ? "border-slate-300 ring-1 ring-slate-200"
              : "border-slate-200"
      }`}
    >
      <div className="flex flex-wrap items-start justify-between gap-3">
        {/* Left: identity */}
        <div className="min-w-0 flex-1">
          <div className="flex flex-wrap items-center gap-2">
            <span
              className={`inline-flex items-center rounded-full border px-2 py-0.5 text-[10px] font-semibold uppercase tracking-wide ${SEVERITY_PILL[alert.severity]}`}
            >
              {SEVERITY_LABEL[alert.severity]}
            </span>
            <span className="text-[11px] font-medium text-slate-500">
              {alert.ruleLabel}
            </span>
            {alert.unread ? (
              <span className="rounded-full bg-blue-100 px-2 py-0.5 text-[10px] font-semibold uppercase tracking-wide text-blue-900">
                Unread
              </span>
            ) : null}
            {alert.snoozed ? (
              <span className="rounded-full bg-slate-200 px-2 py-0.5 text-[10px] font-medium text-slate-700">
                Snoozed until{" "}
                {alert.state?.snoozed_until?.slice(0, 10) ?? "—"}
              </span>
            ) : null}
            {alert.resolved ? (
              <span className="rounded-full bg-emerald-100 px-2 py-0.5 text-[10px] font-medium text-emerald-900">
                Resolved {alert.state?.resolved_at?.slice(0, 10) ?? "—"}
              </span>
            ) : null}
          </div>
          <h2 className="mt-1 text-base font-bold text-slate-900">
            {alert.orgName}
          </h2>
          <div className="mt-1 grid grid-cols-2 gap-x-4 gap-y-1 text-xs text-slate-700 sm:grid-cols-3">
            <Field
              label="MRR"
              value={`£${alert.mrr.toLocaleString("en-GB")}`}
            />
            <Field
              label="Health"
              value={alert.health !== null ? `${alert.health}/100` : "—"}
            />
            <Field label="Risk" value={alert.healthRisk ?? "—"} />
          </div>
          <div className="mt-3">
            <p className="text-[11px] font-semibold uppercase tracking-wide text-slate-500">
              Reason
            </p>
            <ul className="mt-1 list-disc pl-5 text-sm text-slate-800">
              {alert.reason.map((r, idx) => (
                <li key={idx}>{r}</li>
              ))}
            </ul>
          </div>
          <p className="mt-3 text-sm">
            <span className="text-[11px] font-semibold uppercase tracking-wide text-slate-500">
              Suggested action
            </span>
            <br />
            <span className="font-medium text-slate-900">
              {alert.suggestion}
            </span>
          </p>
        </div>

        {/* Right: contact + lifecycle actions */}
        <div className="flex w-full flex-col gap-3 sm:w-auto">
          <div className="flex flex-wrap items-center gap-2">
            {phone ? (
              <a
                href={`tel:${phone}`}
                className="rounded-md border border-slate-300 bg-white px-3 py-1.5 text-xs font-medium text-slate-700 hover:bg-slate-50"
              >
                Call
              </a>
            ) : null}
            {email ? (
              <a
                href={`mailto:${email}`}
                className="rounded-md border border-slate-300 bg-white px-3 py-1.5 text-xs font-medium text-slate-700 hover:bg-slate-50"
              >
                Email
              </a>
            ) : null}
            {phone ? (
              <a
                href={`https://wa.me/${phone.replace(/[^\d]/g, "")}`}
                target="_blank"
                rel="noreferrer noopener"
                className="rounded-md border border-emerald-300 bg-emerald-50 px-3 py-1.5 text-xs font-medium text-emerald-900 hover:bg-emerald-100"
              >
                WhatsApp
              </a>
            ) : null}
            <Link
              href={`/admin/customers/${alert.orgId}`}
              className="rounded-md border border-indigo-300 bg-indigo-50 px-3 py-1.5 text-xs font-medium text-indigo-900 hover:bg-indigo-100"
            >
              Open customer
            </Link>
          </div>
          <div className="flex flex-wrap items-center gap-2">
            {alert.resolved ? (
              <ClientConfirmForm
                action={reopenAlert}
                confirm={`Reopen "${alert.ruleLabel}" for ${alert.orgName}? It will reappear in the active queue.`}
              >
                <input type="hidden" name="rule_id" value={alert.ruleId} />
                <input type="hidden" name="org_id" value={alert.orgId} />
                <button
                  type="submit"
                  className="rounded-md border border-slate-300 bg-white px-3 py-1.5 text-xs font-medium text-slate-700 hover:bg-slate-50"
                >
                  Reopen
                </button>
              </ClientConfirmForm>
            ) : (
              <>
                <ResolveForm ruleId={alert.ruleId} orgId={alert.orgId} />
                <SnoozeForm ruleId={alert.ruleId} orgId={alert.orgId} />
                {alert.unread ? (
                  <form action={markAlertRead}>
                    <input type="hidden" name="rule_id" value={alert.ruleId} />
                    <input type="hidden" name="org_id" value={alert.orgId} />
                    <button
                      type="submit"
                      className="rounded-md border border-slate-300 bg-white px-3 py-1.5 text-xs font-medium text-slate-700 hover:bg-slate-50"
                    >
                      Mark read
                    </button>
                  </form>
                ) : null}
              </>
            )}
          </div>
        </div>
      </div>
    </li>
  );
}

function ResolveForm({ ruleId, orgId }: { ruleId: string; orgId: string }) {
  return (
    <ClientConfirmForm
      action={markAlertResolved}
      confirm="Mark this alert resolved? The notification dedup is cleared so a future re-fire will ping HQ again."
      className="flex items-center gap-1"
    >
      <input type="hidden" name="rule_id" value={ruleId} />
      <input type="hidden" name="org_id" value={orgId} />
      <input
        type="text"
        name="resolution_note"
        placeholder="Note (optional)"
        maxLength={2000}
        className="w-40 rounded-md border border-slate-300 px-2 py-1 text-xs shadow-sm focus:border-slate-500 focus:outline-none focus:ring-1 focus:ring-slate-500"
      />
      <button
        type="submit"
        className="rounded-md bg-emerald-700 px-3 py-1.5 text-xs font-semibold text-white hover:bg-emerald-800"
      >
        Mark resolved
      </button>
    </ClientConfirmForm>
  );
}

function SnoozeForm({ ruleId, orgId }: { ruleId: string; orgId: string }) {
  return (
    <ClientConfirmForm
      action={snoozeAlert}
      confirm="Snooze this alert? It will be hidden from the active queue until the snooze window ends."
      className="flex items-center gap-1"
    >
      <input type="hidden" name="rule_id" value={ruleId} />
      <input type="hidden" name="org_id" value={orgId} />
      <select
        name="preset"
        defaultValue="3d"
        className="rounded-md border border-slate-300 px-2 py-1 text-xs"
      >
        <option value="1d">1 day</option>
        <option value="3d">3 days</option>
        <option value="7d">7 days</option>
        <option value="30d">30 days</option>
      </select>
      <button
        type="submit"
        className="rounded-md border border-slate-300 bg-white px-3 py-1.5 text-xs font-medium text-slate-700 hover:bg-slate-50"
      >
        Snooze
      </button>
    </ClientConfirmForm>
  );
}

