import {
  buildAlertsSnapshot,
  getOwnerContactsForOrgs,
  type OwnerContact,
} from "@/server/services/hq-alerts-snapshot";
import {
  runAlertRules,
  sortAlerts,
  filterAlerts,
  applyStateToAlerts,
  pickActionCentre,
  ALERT_SEVERITIES,
  ALERT_SORTS,
  ALERT_SORT_LABELS,
  SEVERITY_LABEL,
  SEVERITY_PILL,
  THRESHOLDS,
  type Alert,
  type AlertSeverity,
  type AlertSort,
  type AlertWithState,
} from "@/lib/hq/alert-rules";
import {
  markAlertRead,
  markAlertResolved,
  snoozeAlert,
  reopenAlert,
} from "./actions";
import { ClientConfirmForm } from "../_client-confirm";

/**
 * Alerts + AI COO — HQ-5.
 *
 * Single place that surfaces every customer who needs attention,
 * generated by a deterministic rules engine (lib/hq/alert-rules.ts).
 * No LLM — pure rule firings against the existing data.
 *
 * Layout:
 *   1. AI COO panel at the top — "Today needs attention" — picks
 *      the top 3 critical/warning alerts deduped by org.
 *   2. KPI tiles — open critical / open warning / unread / resolved 7d.
 *   3. Filter bar — severity / search / sort / show resolved.
 *   4. List of alerts. Each card carries the directive's full
 *      action set: Call · Email · WhatsApp · Open customer ·
 *      Mark resolved · Snooze · Mark read.
 *
 * Auto-archive: resolved alerts disappear from the default view.
 * The list filters where resolved_at IS NULL unless ?show=resolved.
 *
 * Future-compat: LLM rerankers swap in at pickActionCentre without
 * changing the surrounding page. Channel dispatchers (email /
 * WhatsApp / SMS) iterate the same alert list — no schema work.
 */

type SP = Promise<{
  q?: string;
  severity?: string;
  sort?: string;
  show?: string;
  saved?: string;
  error?: string;
}>;

export default async function HqAlertsPage({
  searchParams,
}: {
  searchParams: SP;
}) {
  const sp = await searchParams;
  const q = (sp.q ?? "").trim();
  const severity = (sp.severity ?? "all") as AlertSeverity | "all";
  const sort = (ALERT_SORTS.includes(sp.sort as AlertSort)
    ? sp.sort
    : "severity") as AlertSort;
  const showResolved = sp.show === "resolved";

  const { snapshot, states } = await buildAlertsSnapshot();
  const baseAlerts = runAlertRules(snapshot);
  const withState = applyStateToAlerts(baseAlerts, states, snapshot.now);

  // Visible set: drop snoozed + resolved unless ?show=resolved.
  const visible = withState.filter((a) => {
    if (a.snoozed) return showResolved;
    if (a.resolved) return showResolved;
    return true;
  });

  const filtered = filterAlerts(visible, { severity, q });
  const sorted = sortAlerts(filtered, sort);

  // AI COO panel — operates on the full visible set, not the
  // filtered one (so the picker doesn't disappear when you search).
  const actionCentre = pickActionCentre(visible);

  // KPIs computed against the full alert set (not the visible
  // filter) so the operator sees system-wide truth.
  const openCritical = withState.filter(
    (a) => a.severity === "critical" && !a.resolved && !a.snoozed,
  ).length;
  const openWarning = withState.filter(
    (a) => a.severity === "warning" && !a.resolved && !a.snoozed,
  ).length;
  const unread = withState.filter((a) => a.unread && !a.snoozed && !a.resolved)
    .length;
  const recentlyResolved = withState.filter((a) => {
    if (!a.resolved || !a.state?.resolved_at) return false;
    const days =
      (Date.now() - new Date(a.state.resolved_at).getTime()) / 86_400_000;
    return days <= 7;
  }).length;

  // Contacts for the action row (one round-trip).
  const orgIds = Array.from(new Set(sorted.map((a) => a.orgId)));
  const contacts = orgIds.length
    ? await getOwnerContactsForOrgs(orgIds)
    : new Map<string, OwnerContact>();

  const banner = (() => {
    if (sp.saved === "1") return { tone: "ok" as const, msg: "Alert updated." };
    if (sp.error === "invalid_input")
      return { tone: "err" as const, msg: "Invalid input — please try again." };
    if (sp.error === "update_failed")
      return {
        tone: "err" as const,
        msg: "Update failed. Check logs for details.",
      };
    return null;
  })();

  return (
    <div className="space-y-6 p-6">
      <header className="flex flex-wrap items-center justify-between gap-3">
        <div>
          <p className="text-[11px] font-semibold uppercase tracking-wider text-slate-500">
            HQ · Alerts
          </p>
          <h1 className="text-2xl font-bold text-slate-900">Action centre</h1>
          <p className="mt-1 max-w-2xl text-sm text-slate-600">
            Deterministic rules engine across every customer. Critical first.
            Resolved alerts auto-archive — toggle &ldquo;Show resolved&rdquo; to bring them back.
          </p>
        </div>
        <div className="flex items-center gap-2">
          <Link
            href="/admin/overview"
            className="rounded-md border border-slate-300 bg-white px-3 py-1.5 text-xs font-medium text-slate-700 hover:bg-slate-50"
          >
            ← HQ overview
          </Link>
        </div>
      </header>

      {banner ? (
        <div
          className={`rounded-md border px-3 py-2 text-sm ${
            banner.tone === "ok"
              ? "border-emerald-200 bg-emerald-50 text-emerald-900"
              : "border-red-200 bg-red-50 text-red-800"
          }`}
        >
          {banner.msg}
        </div>
      ) : null}

      {/* AI COO PANEL ------------------------------------------------- */}
      <CooPanel alerts={actionCentre} />

      {/* KPI tiles --------------------------------------------------- */}
      <section className="grid grid-cols-2 gap-3 md:grid-cols-4">
        <Kpi label="Open critical" value={String(openCritical)} tone="red" />
        <Kpi label="Open warning" value={String(openWarning)} tone="amber" />
        <Kpi label="Unread" value={String(unread)} tone="blue" />
        <Kpi
          label="Resolved this week"
          value={String(recentlyResolved)}
          tone="emerald"
        />
      </section>

      {/* Filter bar -------------------------------------------------- */}
      <form
        method="get"
        action="/admin/alerts"
        className="flex flex-wrap items-end gap-2 rounded-lg border border-slate-200 bg-white p-3 shadow-sm"
      >
        <label className="flex flex-col text-[11px] font-medium text-slate-700">
          Search customer / reason
          <input
            type="text"
            name="q"
            defaultValue={q}
            placeholder="e.g. Adams Roofing or migration"
            className="mt-1 w-64 rounded-md border border-slate-300 px-3 py-1.5 text-sm shadow-sm focus:border-slate-500 focus:outline-none focus:ring-1 focus:ring-slate-500"
          />
        </label>
        <label className="flex flex-col text-[11px] font-medium text-slate-700">
          Severity
          <select
            name="severity"
            defaultValue={severity}
            className="mt-1 rounded-md border border-slate-300 px-2 py-1.5 text-sm"
          >
            <option value="all">All</option>
            {ALERT_SEVERITIES.map((s) => (
              <option key={s} value={s}>
                {SEVERITY_LABEL[s]}
              </option>
            ))}
          </select>
        </label>
        <label className="flex flex-col text-[11px] font-medium text-slate-700">
          Sort by
          <select
            name="sort"
            defaultValue={sort}
            className="mt-1 rounded-md border border-slate-300 px-2 py-1.5 text-sm"
          >
            {ALERT_SORTS.map((s) => (
              <option key={s} value={s}>
                {ALERT_SORT_LABELS[s]}
              </option>
            ))}
          </select>
        </label>
        <label className="flex items-center gap-2 text-[11px] font-medium text-slate-700">
          <input
            type="checkbox"
            name="show"
            value="resolved"
            defaultChecked={showResolved}
          />
          Show resolved + snoozed
        </label>
        <button
          type="submit"
          className="rounded-md bg-slate-900 px-3 py-1.5 text-xs font-semibold text-white hover:bg-slate-700"
        >
          Apply
        </button>
        <Link
          href="/admin/alerts"
          className="rounded-md border border-slate-300 bg-white px-3 py-1.5 text-xs font-medium text-slate-700 hover:bg-slate-50"
        >
          Reset
        </Link>
      </form>

      {/* Alert list -------------------------------------------------- */}
      {sorted.length === 0 ? (
        <p className="rounded-md border border-dashed border-slate-300 bg-white px-4 py-6 text-center text-sm text-slate-500">
          No alerts match these filters.{" "}
          {!showResolved
            ? "Resolved alerts are hidden — toggle 'Show resolved' to bring them back."
            : ""}
        </p>
      ) : (
        <ul className="space-y-3">
          {sorted.map((a) => (
            <AlertCard key={a.key} alert={a} contact={contacts.get(a.orgId)} />
          ))}
        </ul>
      )}

      <FooterMeta count={sorted.length} totalRules={withState.length} />
    </div>
  );
}

