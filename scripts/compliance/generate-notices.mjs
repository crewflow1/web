#!/usr/bin/env node
/**
 * Generate THIRD-PARTY-NOTICES.md from docs/compliance/licence-inventory.json.
 *
 * Scope: every PRODUCTION-graph package (scope prod | prod-optional) — i.e. what Vercel installs for
 * `next build`/runtime — with its licence text, grouped by identical text where possible.
 * Dev-only tooling is excluded (it is never shipped or deployed). Platform-specific optional binaries
 * not present on disk are listed by name/version/licence only (the text is identical to a sibling).
 * Non-npm bundled material (fonts, pdf.js worker, data) is appended from a static block.
 *
 * Usage: node scripts/compliance/generate-notices.mjs [--fallback <dir>]
 */
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";

const root = process.cwd();
const fbi = process.argv.indexOf("--fallback");
const fallback = fbi > 0 ? path.resolve(process.argv[fbi + 1]) : null;
const rows = JSON.parse(fs.readFileSync("docs/compliance/licence-inventory.json", "utf8"));
const prod = rows.filter((r) => r.scope === "prod" || r.scope === "prod-optional");

function dirFor(r) {
  for (const base of [root, fallback].filter(Boolean)) {
    const d = path.join(base, r.path);
    try {
      if (JSON.parse(fs.readFileSync(path.join(d, "package.json"), "utf8")).version === r.version) return d;
    } catch {}
  }
  return null;
}
const read = (p) => { try { return fs.readFileSync(p, "utf8").replace(/\r\n/g, "\n").trim(); } catch { return ""; } };

const groups = new Map(); // hash -> {text, pkgs[]}
const noText = [];
const notices = [];
for (const r of prod) {
  const d = dirFor(r);
  let text = "";
  if (d) {
    for (const f of (r.license_files || "").split("|").filter(Boolean)) {
      if (/^notice/i.test(f)) continue;
      text += (text ? "\n\n" : "") + read(path.join(d, f));
    }
    for (const f of (r.notice_files || "").split("|").filter(Boolean)) notices.push({ r, text: read(path.join(d, f)) });
  }
  text = text.trim();
  if (!text) { noText.push(r); continue; }
  const h = crypto.createHash("sha256").update(text).digest("hex");
  (groups.get(h) || groups.set(h, { text, pkgs: [] }).get(h)).pkgs.push(r);
}

const lines = [];
const P = (s = "") => lines.push(s);
P("# Third-party notices");
P();
P("CrewFlow includes software developed by third parties. This file reproduces the copyright notices and licence texts that those licences require us to carry. It covers the **production dependency graph** (what is installed to build and run the product) as recorded in `package-lock.json`; development-only tooling (test runners, linters, type-checkers) is not shipped and is not listed.");
P();
P("Generated by `scripts/compliance/generate-notices.mjs` from `docs/compliance/licence-inventory.csv`. Regenerate after any dependency change. Do not edit by hand.");
P();
P(`Packages covered: ${prod.length}. Distinct licence texts reproduced below: ${groups.size}.`);
P();
P("## Where the obligation actually bites");
P();
P("- **Code served to browsers** (client bundles, the pdf.js worker, fonts) is *distributed*; MIT/ISC/BSD/Apache-2.0 require the copyright and licence notice to accompany it. This file, once published at a public URL (see FOUNDER-CONFIRMATIONS.md Q3), is the mechanism.");
P("- **Server-only code** (Vercel serverless functions) is not distributed; the same notices are included here anyway as good practice and in case a customer or auditor asks.");
P("- Dual-licensed components are used under the permissive option: `jszip` under MIT (not GPL-3.0), `dompurify` under Apache-2.0 (not MPL-2.0), `type-fest` under MIT (not CC0).");
P("- `sharp`/`libvips` (image optimisation, LGPL-3.0-or-later for the libvips binary) runs server-side only and is dynamically loaded as a separate shared library; nothing is statically linked into CrewFlow code and nothing is distributed. See LICENCE-REGISTER.md.");
P();
P("## Non-npm material bundled with the product");
P();
P("### Clash Display and Satoshi (typefaces)");
P();
P("Copyright 2021 Indian Type Foundry (Clash Display); Copyright 2017-2021 Indian Type Foundry (Satoshi; designer Deni Anggara). \"Clash\" and \"Satoshi\" are trademarks of the Indian Type Foundry. Used under the ITF Free Font License as published at https://fontshare.com/terms and self-hosted from `app/_marketing/fonts/`. Fonts credited to Indian Type Foundry (https://www.fontshare.com).");
P();
P("### Inter (typeface)");
P();
P("Copyright 2020 The Inter Project Authors (https://github.com/rsms/inter). Licensed under the SIL Open Font License, Version 1.1 (https://openfontlicense.org). Loaded through `next/font/google`, which downloads the font files at build time and serves them from CrewFlow's own origin.");
P();
P("### PDF.js worker (`public/pdf.worker.min.mjs`)");
P();
P("Copied by `scripts/copy-pdf-worker.mjs` from `pdfjs-dist` at build time. Copyright 2024 Mozilla Foundation. Licensed under the Apache License, Version 2.0. The licence header is retained inside the minified file.");
P();
P("### libphonenumber metadata");
P();
P("`libphonenumber-js` is MIT (c) catamphetamine. Its phone-number metadata is derived from Google's libphonenumber, Copyright (C) Google Inc., licensed under the Apache License, Version 2.0 (ships as `LICENSE.Apache` inside the package; reproduced below under that package).");
P();
P("### Lucide icons");
P();
P("`lucide-react` (ISC). Portions Copyright (c) Cole Bemis 2013-2022 as part of Feather (MIT). Reproduced below under that package.");
P();
P("### UK postcode-district centroids (`lib/weather/geo/district-centroids.ts`)");
P();
P("Contains OS data © Crown copyright and database right 2026. Contains Royal Mail data © Royal Mail copyright and database right 2026. Contains GeoPlace data © Local Government Information House Limited copyright and database right 2026. Source: Office for National Statistics licensed under the Open Government Licence v.3.0 (https://www.nationalarchives.gov.uk/doc/open-government-licence/version/3/).");
P();
P("### Weather data (when the weather feature is activated)");
P();
P("Weather data by Open-Meteo.com (https://open-meteo.com/), licensed under CC BY 4.0. Rendered in-product wherever the data appears (`app/(app)/weather/page.tsx`).");
P();
P("## Apache-2.0 NOTICE files shipped by production packages");
P();
if (!notices.length) P("None.");
for (const n of notices) { P(`### ${n.r.name} ${n.r.version}`); P(); P("```"); P(n.text); P("```"); P(); }
P("## npm packages by licence text");
P();
const sorted = [...groups.values()].sort((a, b) => b.pkgs.length - a.pkgs.length || a.pkgs[0].name.localeCompare(b.pkgs[0].name));
for (const g of sorted) {
  const names = g.pkgs.map((p) => `${p.name}@${p.version}`);
  const uniq = [...new Set(names)].sort();
  P(`### ${uniq.length === 1 ? uniq[0] : uniq.slice(0, 3).join(", ") + (uniq.length > 3 ? ` and ${uniq.length - 3} more` : "")}`);
  P();
  P(`Applies to: ${uniq.join(", ")}`);
  P();
  P("```");
  P(g.text);
  P("```");
  P();
}
if (noText.length) {
  P("## Packages whose licence text was not available for reproduction");
  P();
  P("These are in the production graph (platform-specific optional binaries not installed on the build machine, or packages that ship no licence file). Their licence is recorded from `package.json`/`package-lock.json`; fetch the text from the package's registry page if a customer or auditor requires it.");
  P();
  P("| Package | Version | Declared licence | Reason |");
  P("|---|---|---|---|");
  for (const r of noText.sort((a, b) => a.name.localeCompare(b.name)))
    P(`| ${r.name} | ${r.version} | ${r.effective_license || "(none declared)"} | ${r.source === "lock-only" ? "not installed on this machine (platform-specific optional)" : "package ships no LICENSE file"} |`);
  P();
}
fs.writeFileSync("docs/compliance/THIRD-PARTY-NOTICES.md", lines.join("\n") + "\n");
console.log({ prod: prod.length, groups: groups.size, noText: noText.length, notices: notices.length, bytes: lines.join("\n").length });
